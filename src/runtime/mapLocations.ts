// Return undefined for unknown places so tests can detect accidental corridor fallbacks.
export function knownMapPoint(place: string): readonly [number, number] | undefined {
  const room = mapRooms.find(([name]) => name === place);
  return room ? [room[1], room[2] + 15] : mapLandmarks[place];
}
export function mapPoint(place: string): readonly [number, number] {
  return knownMapPoint(place) ?? mapLandmarks["长廊"]!;
}
